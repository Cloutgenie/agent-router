export function findDemoCompany(name: string): DemoCompany | undefined {
  return DEMO_COMPANIES.find((c) => c.name === name);
}

/** Deterministic-ish shuffle-and-slice for discovery step sampling. */
export function sampleDemoCompanies(count: number): DemoCompany[] {
  const shuffled = [...DEMO_COMPANIES].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}
